/**
 * Paste handling for the Markdown editor.
 *
 * Three pastes matter in a notes application: a URL over a selection, rich
 * text from a browser or a document, and an image file. The first two are
 * handled here. Image files keep the existing upload path in the note
 * screen, so this module declines them.
 *
 * The HTML to Markdown converter below is deliberately small and has no
 * dependency. It reads the tags a copied web page or document actually
 * carries and drops the rest, which keeps the pasted text clean instead of
 * faithful. Because it parses text and not a DOM, it runs in a unit test
 * without a browser.
 */
import { EditorView } from '@codemirror/view';
import {
  EditorSelection,
  type EditorState,
  type Extension,
} from '@codemirror/state';
import { withNoteLinks } from './completion.ts';
import { insideLiteral } from './literal-context.ts';
import { insideCodeFence } from './keymaps.ts';

/** Elements that never hold content. */
const voidTags = new Set([
  'area',
  'base',
  'br',
  'col',
  'embed',
  'hr',
  'img',
  'input',
  'link',
  'meta',
  'param',
  'source',
  'track',
  'wbr',
]);

/** Elements dropped with everything inside them. */
const droppedTags = new Set(['script', 'style', 'head', 'title', 'noscript']);

/** One parsed HTML element. */
type HtmlElement = {
  readonly kind: 'element';
  readonly tag: string;
  readonly attributes: ReadonlyMap<string, string>;
  readonly children: HtmlNode[];
};

/** One parsed HTML node. */
type HtmlNode = { readonly kind: 'text'; readonly value: string } | HtmlElement;

/** Matches a comment, a tag, or a run of text. */
const tokenPattern =
  /<!--[\s\S]*?-->|<!\[CDATA\[[\s\S]*?\]\]>|<[!?][^>]*>|<\/([a-zA-Z][\w:-]*)\s*>|<([a-zA-Z][\w:-]*)((?:\s+[^\s"'>/=]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s"'>`]+))?)*)\s*(\/?)>|[^<]+/g;

/** Matches one attribute of a start tag. */
const attributePattern =
  /([^\s"'>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>`]+)))?/g;

/** The named entities a pasted document realistically carries. */
const namedEntities = new Map<string, string>([
  ['amp', '&'],
  ['lt', '<'],
  ['gt', '>'],
  ['quot', '"'],
  ['apos', "'"],
  ['nbsp', ' '],
  ['mdash', '-'],
  ['ndash', '-'],
  ['hellip', '...'],
  ['rsquo', "'"],
  ['lsquo', "'"],
  ['rdquo', '"'],
  ['ldquo', '"'],
]);

/** Replaces HTML entities with their characters. */
export function decodeEntities(value: string): string {
  return value.replace(
    /&(#x?[0-9a-fA-F]+|[a-zA-Z]+);/g,
    (whole, body: string) => {
      if (body.startsWith('#x') || body.startsWith('#X')) {
        const code = Number.parseInt(body.slice(2), 16);
        return Number.isFinite(code) ? String.fromCodePoint(code) : whole;
      }
      if (body.startsWith('#')) {
        const code = Number.parseInt(body.slice(1), 10);
        return Number.isFinite(code) ? String.fromCodePoint(code) : whole;
      }
      return namedEntities.get(body.toLowerCase()) ?? whole;
    },
  );
}

/** Reads the attributes of one start tag. */
function readAttributes(source: string): ReadonlyMap<string, string> {
  const attributes = new Map<string, string>();
  attributePattern.lastIndex = 0;
  for (;;) {
    const match = attributePattern.exec(source);
    if (match === null) return attributes;
    const name = (match[1] ?? '').toLowerCase();
    if (name === '') continue;
    const value = match[2] ?? match[3] ?? match[4] ?? '';
    attributes.set(name, decodeEntities(value));
  }
}

/** Tags that close an open `p` or `li` when they open. */
const closesParagraph = new Set([
  'address',
  'blockquote',
  'div',
  'dl',
  'fieldset',
  'form',
  'h1',
  'h2',
  'h3',
  'h4',
  'h5',
  'h6',
  'hr',
  'li',
  'ol',
  'p',
  'pre',
  'section',
  'table',
  'ul',
]);

/**
 * Parses HTML into a tolerant tree.
 *
 * Unknown tags stay in the tree and render as their content, unmatched close
 * tags are ignored, and an unclosed `p`, `li`, `td`, `th` or `tr` closes when
 * the next block starts. This is enough for clipboard HTML, which is
 * generated by a browser and is nearly always well formed.
 */
export function parseHtml(html: string): HtmlNode[] {
  const root: HtmlElement = {
    kind: 'element',
    tag: '#root',
    attributes: new Map(),
    children: [],
  };
  const stack: HtmlElement[] = [root];
  const top = (): HtmlElement => {
    const last = stack.at(-1);
    if (last === undefined) throw new Error('The HTML stack is empty.');
    return last;
  };
  const closeTag = (tag: string): void => {
    const index = stack.findLastIndex((node) => node.tag === tag);
    if (index <= 0) return;
    stack.length = index;
  };
  tokenPattern.lastIndex = 0;
  for (;;) {
    const match = tokenPattern.exec(html);
    if (match === null) break;
    const whole = match[0];
    const closing = match[1];
    const opening = match[2];
    if (closing !== undefined) {
      closeTag(closing.toLowerCase());
      continue;
    }
    if (opening !== undefined) {
      const tag = opening.toLowerCase();
      const attributes = readAttributes(match[3] ?? '');
      if (droppedTags.has(tag)) {
        // Skip to the matching close tag, so no script text becomes content.
        const end = html.toLowerCase().indexOf(`</${tag}>`, match.index);
        tokenPattern.lastIndex =
          end === -1 ? html.length : end + tag.length + 3;
        continue;
      }
      if (
        (top().tag === 'p' && closesParagraph.has(tag)) ||
        (top().tag === 'li' && (tag === 'li' || tag === 'p')) ||
        (['td', 'th'].includes(top().tag) &&
          ['td', 'th', 'tr'].includes(tag)) ||
        (top().tag === 'tr' && tag === 'tr')
      )
        closeTag(top().tag);
      const node: HtmlElement = {
        kind: 'element',
        tag,
        attributes,
        children: [],
      };
      top().children.push(node);
      if (!voidTags.has(tag) && match[4] !== '/') stack.push(node);
      continue;
    }
    if (whole.startsWith('<')) continue;
    top().children.push({ kind: 'text', value: whole });
  }
  return root.children;
}

/**
 * Escapes the Markdown characters that would change the meaning of text.
 *
 * A dollar is one of them, because one dollar opens math (record 0171).
 */
function escapeMarkdown(value: string): string {
  return value.replace(/([\\`*[\]$])/g, '\\$1');
}

/** Collapses HTML white space the way a browser renders it. */
function collapse(value: string): string {
  return value.replace(/\s+/g, ' ');
}

/** The plain text of a subtree, used for table cells and code blocks. */
function plainText(nodes: readonly HtmlNode[]): string {
  return nodes
    .map((node) =>
      node.kind === 'text'
        ? decodeEntities(node.value)
        : node.tag === 'br'
          ? '\n'
          : plainText(node.children),
    )
    .join('');
}

/** Prefixes every line of a block, used for block quotes and list items. */
function prefixLines(value: string, first: string, rest: string): string {
  const lines = value.split('\n');
  return lines
    .map((line, index) =>
      index === 0
        ? `${first}${line}`
        : line === ''
          ? rest.trimEnd()
          : `${rest}${line}`,
    )
    .join('\n');
}

/** Renders the inline content of one element. */
function renderInline(nodes: readonly HtmlNode[]): string {
  let out = '';
  for (const node of nodes) {
    if (node.kind === 'text') {
      out += escapeMarkdown(collapse(decodeEntities(node.value)));
      continue;
    }
    const inner = renderInline(node.children);
    switch (node.tag) {
      case 'br':
        out += '  \n';
        break;
      case 'strong':
      case 'b':
        out += inner.trim() === '' ? inner : `**${inner.trim()}**`;
        break;
      case 'em':
      case 'i':
        out += inner.trim() === '' ? inner : `*${inner.trim()}*`;
        break;
      case 'del':
      case 's':
      case 'strike':
        out += inner.trim() === '' ? inner : `~~${inner.trim()}~~`;
        break;
      case 'code':
      case 'kbd':
      case 'samp':
        out += `\`${plainText(node.children).trim()}\``;
        break;
      case 'a': {
        const href = node.attributes.get('href') ?? '';
        out += href === '' ? inner : `[${inner.trim()}](${href})`;
        break;
      }
      case 'img': {
        const source = node.attributes.get('src') ?? '';
        const alt = node.attributes.get('alt') ?? '';
        out += source === '' ? '' : `![${alt}](${source})`;
        break;
      }
      default:
        out += inner;
    }
  }
  return out;
}

/** Renders one table row as a GFM row, or null when it holds no cell. */
function renderRow(node: HtmlElement): {
  readonly cells: readonly string[];
  readonly header: boolean;
} | null {
  const cells = node.children.filter(
    (child): child is HtmlElement =>
      child.kind === 'element' && (child.tag === 'td' || child.tag === 'th'),
  );
  if (cells.length === 0) return null;
  return {
    cells: cells.map((cell) =>
      renderInline(cell.children).replaceAll('|', '\\|').trim(),
    ),
    header: cells.every((cell) => cell.tag === 'th'),
  };
}

/** Collects every table row of a table, in document order. */
function tableRows(node: HtmlElement): readonly HtmlElement[] {
  const rows: HtmlElement[] = [];
  const walk = (current: readonly HtmlNode[]): void => {
    for (const child of current) {
      if (child.kind !== 'element') continue;
      if (child.tag === 'tr') rows.push(child);
      else walk(child.children);
    }
  };
  walk(node.children);
  return rows;
}

/** Renders a table as GFM, or null when it has no usable row. */
function renderTable(node: HtmlElement): string | null {
  const rows = tableRows(node)
    .map((row) => renderRow(row))
    .filter(
      (row): row is { cells: readonly string[]; header: boolean } =>
        row !== null,
    );
  const first = rows[0];
  if (first === undefined) return null;
  const width = Math.max(...rows.map((row) => row.cells.length));
  const pad = (cells: readonly string[]): string =>
    `| ${Array.from({ length: width }, (_, index) => cells[index] ?? '').join(' | ')} |`;
  const body = first.header ? rows.slice(1) : rows;
  const head = first.header
    ? first.cells
    : Array.from({ length: width }, () => '');
  const divider = `| ${Array.from({ length: width }, () => '---').join(' | ')} |`;
  return [pad(head), divider, ...body.map((row) => pad(row.cells))].join('\n');
}

/** Matches the first line of a nested list inside a list item. */
const nestedListStart = /\n\n(?=(?:[-*+]|\d+[.)]) )/g;

/**
 * Renders the list items of a `ul` or an `ol`.
 *
 * A nested list is indented by the width of its parent marker, and the blank
 * line the block renderer puts before it is removed, so the list stays tight
 * and reads the way it was copied.
 */
function renderList(node: HtmlElement, depth: number): string {
  const ordered = node.tag === 'ol';
  const items = node.children.filter(
    (child): child is HtmlElement =>
      child.kind === 'element' && child.tag === 'li',
  );
  return items
    .map((item, index) => {
      const marker = ordered ? `${String(index + 1)}. ` : '- ';
      const content = renderBlocks(item.children, depth + 1)
        .trim()
        .replace(nestedListStart, '\n');
      return prefixLines(content, marker, ' '.repeat(marker.length));
    })
    .join('\n');
}

/** Renders a `pre` block as a fenced code block. */
function renderPre(node: HtmlElement): string {
  const code = node.children.find(
    (child): child is HtmlElement =>
      child.kind === 'element' && child.tag === 'code',
  );
  const classes = (code?.attributes.get('class') ?? '').split(/\s+/);
  const language =
    classes
      .find((name) => name.startsWith('language-'))
      ?.slice('language-'.length) ?? '';
  const text = plainText(code === undefined ? node.children : code.children);
  return `\`\`\`${language}\n${text.replace(/\n+$/, '')}\n\`\`\``;
}

/** The block level tags this converter understands. */
const blockTags = new Set([
  'address',
  'article',
  'aside',
  'blockquote',
  'div',
  'footer',
  'h1',
  'h2',
  'h3',
  'h4',
  'h5',
  'h6',
  'header',
  'hr',
  'main',
  'nav',
  'ol',
  'p',
  'pre',
  'section',
  'table',
  'ul',
]);

/** Renders a sequence of nodes as Markdown blocks. */
function renderBlocks(nodes: readonly HtmlNode[], depth: number): string {
  const blocks: string[] = [];
  let inline = '';
  const flush = (): void => {
    const trimmed = inline.replace(/[ \t]+$/, '').trim();
    inline = '';
    if (trimmed !== '') blocks.push(trimmed);
  };
  for (const node of nodes) {
    if (node.kind === 'text') {
      inline += escapeMarkdown(collapse(decodeEntities(node.value)));
      continue;
    }
    if (!blockTags.has(node.tag)) {
      inline += renderInline([node]);
      continue;
    }
    flush();
    switch (node.tag) {
      case 'h1':
      case 'h2':
      case 'h3':
      case 'h4':
      case 'h5':
      case 'h6': {
        const level = Number.parseInt(node.tag.slice(1), 10);
        const text = renderInline(node.children).trim();
        if (text !== '') blocks.push(`${'#'.repeat(level)} ${text}`);
        break;
      }
      case 'hr':
        blocks.push('---');
        break;
      case 'pre':
        blocks.push(renderPre(node));
        break;
      case 'blockquote': {
        const inner = renderBlocks(node.children, depth).trim();
        if (inner !== '') blocks.push(prefixLines(inner, '> ', '> '));
        break;
      }
      case 'ul':
      case 'ol': {
        const list = renderList(node, depth);
        if (list.trim() !== '') blocks.push(list);
        break;
      }
      case 'table': {
        const table = renderTable(node);
        if (table !== null) blocks.push(table);
        break;
      }
      case 'p': {
        const text = renderInline(node.children).trim();
        if (text !== '') blocks.push(text);
        break;
      }
      default: {
        const inner = renderBlocks(node.children, depth).trim();
        if (inner !== '') blocks.push(inner);
      }
    }
  }
  flush();
  return blocks.join('\n\n');
}

/**
 * Converts clipboard HTML into Markdown.
 *
 * Headings, paragraphs, bold, italic, strike through, inline code, code
 * blocks, links, images, lists, block quotes, horizontal rules and tables are
 * converted. Everything else contributes its text, so nothing is lost and no
 * markup survives.
 */
export function htmlToMarkdown(html: string): string {
  const nodes = parseHtml(html);
  const body = findBody(nodes);
  const rendered = renderBlocks(body === null ? nodes : body.children, 0);
  return rendered.replace(/\n{3,}/g, '\n\n').trim();
}

/** Finds the `body` element of a whole clipboard document, if there is one. */
function findBody(nodes: readonly HtmlNode[]): HtmlElement | null {
  for (const node of nodes) {
    if (node.kind !== 'element') continue;
    if (node.tag === 'body') return node;
    const nested = findBody(node.children);
    if (nested !== null) return nested;
  }
  return null;
}

/** Matches a pasted link destination. */
const pastedUrlPattern = /^(?:https?:\/\/|mailto:|xmpp:|www\.)\S+$/i;

/** Reports whether the pasted text is a single link destination. */
export function isPastedUrl(text: string): boolean {
  return pastedUrlPattern.test(text.trim());
}

/** Adds the scheme a bare `www.` address needs. */
export function normalizePastedUrl(text: string): string {
  const trimmed = text.trim();
  return /^www\./i.test(trimmed) ? `https://${trimmed}` : trimmed;
}

/**
 * The Markdown that a paste of text writes at the selection, or `null` to
 * leave the paste to the editor, which writes the plain text.
 *
 * Inside code, math, HTML or a link every paste is literal text, rich or
 * plain, as it is inside a fence: Markdown there is characters, so a mark or
 * an escape of a converted page would show as it is written. Anywhere else,
 * rich text becomes Markdown when that adds something over the plain text.
 * Its characters are the characters of the page that the person copied, so a
 * `[[` in it stays a `[[`, escaped. A wiki link of plain text, as a copy of
 * the source of a vault holds, becomes a standard link when its note is there
 * (record 0172).
 */
export function pastedMarkdown(
  state: EditorState,
  plain: string,
  html: string,
): string | null {
  if (insideLiteral(state, state.selection.main.from)) return null;
  const converted = html === '' ? '' : htmlToMarkdown(html);
  if (converted !== '' && converted !== plain.trim()) return converted;
  const linked = withNoteLinks(state, plain);
  return linked === plain ? null : linked;
}

/**
 * The paste handler of the Markdown editor.
 *
 * Order matters. Files stay with the note screen, which uploads them.
 * Inside a code fence every paste stays literal. A URL over a selection
 * becomes a link, and every other paste writes what `pastedMarkdown` answers,
 * which keeps a paste inside code, math, HTML or a link literal as well.
 */
export const markdownPaste: Extension = EditorView.domEventHandlers({
  paste: (event: ClipboardEvent, view: EditorView): boolean => {
    const data = event.clipboardData;
    if (data === null || view.state.readOnly) return false;
    if (data.files.length > 0) return false;
    const main = view.state.selection.main;
    const line = view.state.doc.lineAt(main.from);
    if (insideCodeFence(view.state, line.number)) return false;

    const plain = data.getData('text/plain');
    if (!main.empty && isPastedUrl(plain)) {
      const url = normalizePastedUrl(plain);
      view.dispatch({
        changes: [
          { from: main.from, insert: '[' },
          { from: main.to, insert: `](${url})` },
        ],
        selection: EditorSelection.cursor(main.to + `](${url})`.length + 1),
        userEvent: 'input.paste',
        scrollIntoView: true,
      });
      return true;
    }

    const markdown = pastedMarkdown(
      view.state,
      plain,
      data.getData('text/html'),
    );
    if (markdown === null) return false;
    view.dispatch({
      changes: { from: main.from, to: main.to, insert: markdown },
      selection: EditorSelection.cursor(main.from + markdown.length),
      userEvent: 'input.paste',
      scrollIntoView: true,
    });
    return true;
  },
});
