import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  composeRootGuide,
  guidedDirectories,
  maximumGuideLines,
} from './check-agents-md.mjs';

// The fixtures below are disposable trees under the system temporary
// directory. They are never committed as application code.
const checker = fileURLToPath(
  new URL('./check-agents-md.mjs', import.meta.url),
);

/**
 * A guide body of the given length, in lines.
 *
 * @param {number} [lines]
 * @returns {string}
 */
function guide(lines = 3) {
  /** @type {string[]} */
  const body = ['# Fixture', ''];
  while (body.length < lines) body.push('Text.');
  return `${body.slice(0, lines).join('\n')}\n`;
}

/**
 * @param {Record<string, string>} overrides
 * @returns {{ status: number; output: string }}
 */
function check(overrides) {
  const directory = mkdtempSync(join(tmpdir(), 'notesapp-guides-'));
  try {
    const rules = [
      { name: '01-communication.md', text: '# Communication\n\n- One rule.\n' },
      { name: '02-git.md', text: '# Git\n\n- Another rule.\n' },
    ];
    /** @type {Record<string, string>} */
    const files = { 'AGENTS.md': composeRootGuide(rules) };
    for (const rule of rules) files[`rules/${rule.name}`] = rule.text;
    for (const guided of guidedDirectories)
      files[`${guided}/AGENTS.md`] = guide();
    for (const [name, content] of Object.entries({ ...files, ...overrides })) {
      if (content === '') continue;
      const file = join(directory, name);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
    const result = spawnSync(process.execPath, [checker, '--root', directory], {
      encoding: 'utf8',
    });
    return {
      status: result.status ?? 1,
      output: `${result.stdout ?? ''}${result.stderr ?? ''}`,
    };
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

await test('the composed guide matches the shape that rules/link.sh writes', () => {
  const composed = composeRootGuide([
    { name: '02-git.md', text: '# Git\n\n- B.\n' },
    { name: '01-communication.md', text: '# Communication\n\n- A.\n' },
  ]);
  assert.equal(
    composed,
    '# Generated by rules/link.sh. Do not edit this file.\n\n' +
      'Edit files in `rules/` and run `rules/link.sh`.\n\n' +
      '# Communication\n\n- A.\n\n# Git\n\n- B.\n',
  );
});

await test('a complete tree passes', () => {
  const result = check({});
  assert.equal(result.status, 0, result.output);
  assert.match(result.output, /2 rule files/);
});

await test('a root guide that drifts from the rules fails', () => {
  const result = check({ 'AGENTS.md': '# Hand written.\n' });
  assert.equal(result.status, 1);
  assert.match(result.output, /Run rules\/link\.sh/);
});

await test('a missing directory guide fails and names the directory', () => {
  const result = check({ 'packages/core/AGENTS.md': '' });
  assert.equal(result.status, 1);
  assert.match(result.output, /packages\/core\/AGENTS\.md: missing/);
});

await test('a directory guide over the line budget fails', () => {
  const result = check({
    'packages/ui/AGENTS.md': guide(maximumGuideLines + 1),
  });
  assert.equal(result.status, 1);
  assert.match(result.output, /packages\/ui\/AGENTS\.md: 81 lines/);
});
