#!/bin/sh
set -eu

rules_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_dir=$(dirname -- "$rules_dir")
target="$repo_dir/AGENTS.md"
temporary=$(mktemp "$repo_dir/.AGENTS.md.XXXXXX")
trap 'rm -f "$temporary"' EXIT HUP INT TERM

{
  printf '%s\n\n' '# Generated by rules/link.sh. Do not edit this file.'
  printf '%s\n\n' 'Edit files in `rules/` and run `rules/link.sh`.'
  first_rule=true
  for rule in "$rules_dir"/[0-9][0-9]-*.md; do
    if [ "$first_rule" = false ]; then
      printf '\n'
    fi
    cat "$rule"
    first_rule=false
  done
} > "$temporary"

mv "$temporary" "$target"
trap - EXIT HUP INT TERM
